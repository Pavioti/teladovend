    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(jTextField1.getText().isEmpty() ||
           jTextField2.getText().isBlank() ||     
           jTextField3.getText().isBlank() ||
           jTextField4.getText().isBlank())
           {
              JOptionPane.showMessageDialog(this,"Os campos não podem estar vazios");
           }
        else
        {
            String codigo, descricao, data;
            float preco;
            codigo = jTextField1.getText();
            descricao = jTextField2.getText();
            data = jTextField4.getText();
            preco = Float.parseFloat(jTextField3.getText());
            
            DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

            modelo.addRow(new Object[]{codigo, descricao, preco, data});   
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

